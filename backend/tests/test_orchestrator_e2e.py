def offline_responder(request, context):
    schema = request.response_schema
    if schema and "tasks" in schema.get("properties", {}):
        return json.dumps({"tasks": [
            {"key": "backend", "title": "Implement backend API", "agent": "backend_engineer",
             "phase": "implementation", "description": "Create backend service files",
             "depends_on": [], "validation_criteria": ["File exists"], "priority": 8},
            {"key": "frontend", "title": "Implement frontend UI", "agent": "frontend_engineer",
             "phase": "implementation", "description": "Create frontend source files",
             "depends_on": ["backend"], "validation_criteria": ["File exists"], "priority": 7},
            {"key": "tests", "title": "Write and run tests", "agent": "qa_engineer",
             "phase": "testing", "description": "Create tests and run them",
             "depends_on": ["frontend"], "validation_criteria": ["Tests run"], "priority": 6},
        ]})
    if "TOOL RESULTS" in context:
        return "Completed and verified with tool evidence"
    if request.phase in ("implementation", "testing"):
        paths = {
            "backend_engineer": "backend/generated/service.py",
            "frontend_engineer": "frontend/generated/page.tsx",
            "qa_engineer": "tests/test_generated.py",
        }
        path = paths.get(request.agent_id, f"generated/{request.agent_id}.txt")
        return json.dumps({"tool_calls": [
            {"name": "file_write", "arguments": {"path": path, "content":
                f"# Generated by {request.agent_id}\nVALUE = 'ok'\n"}},
            {"name": "shell_run", "arguments": {"command": "echo build-ok"}},
        ]})
    if schema:
        return json.dumps(MockProvider._value(schema, context))
    return f"Completed {request.agent_id} task"


